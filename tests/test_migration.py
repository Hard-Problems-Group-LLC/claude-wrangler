def test_adoption_reports_mismatches(tmp_path):
    good = tmp_path / "good"
    bad = tmp_path / "bad"
    good.write_bytes(b"right bytes")
    bad.write_bytes(b"wrong bytes")
    import hashlib

    digest = hashlib.sha256(b"right bytes").hexdigest()
    result = find_adoptable_binary([bad, good], len(b"right bytes"), digest)
    assert result.source == good
    assert len(result.notes) == 1 and "SHA-256" in result.notes[0]


