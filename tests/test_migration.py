def test_failure_after_the_commit_point_is_finished_by_the_next_install(
    project, monkeypatch
):
    root = make_legacy(project)
    source = standard_source()
    original = operations.atomic_write_text

    def fail_projection(path, text, *args, **kwargs):
        """Fail the projection write (after the schema-2 commit point)."""

        if Path(path).parent == root:
            raise OSError("simulated failure writing the projection")
        return original(path, text, *args, **kwargs)

    monkeypatch.setattr(operations, "atomic_write_text", fail_projection)
    with pytest.raises(OSError):
        install(project, source)
    assert native_metadata(project)["legacy_migrated_from"] == LEGACY
    monkeypatch.setattr(operations, "atomic_write_text", original)

    assert install(project, source) == 0

    projection = json.loads((root / METADATA_FILENAME).read_text("utf-8"))
    assert "migrated_to" in projection
    assert sorted(os.listdir(root)) == [METADATA_FILENAME]
    assert source.downloads == []


