CUSTOM = "tools/claude-npm"


def npm_era_launcher(
    local_dir: str,
    newline: str = "\n",
    config_dir: str = ".local/claude",
    home_dir: str = ".local/claude/HOME",
) -> str:
    """Return a launcher shaped like the npm-era bash template."""

    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# managed by claude-wrangler",
        "# Generated by claude-wrangler",
        "",
        'repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"',
        'local_prefix="$repo_root/' + local_dir + '"',
        'export NPM_CONFIG_CACHE="$local_prefix/.npm-cache"',
        'export CLAUDE_LOCAL_MANAGED_BY="claude-wrangler"',
        'export CLAUDE_CONFIG_DIR="$repo_root/' + config_dir + '"',
        'if [[ "$shared_home" != "1" ]]; then',
        '  export HOME="$repo_root/' + home_dir + '"',
        "fi",
        'local_claude_bin="$local_prefix/node_modules/.bin/claude"',
        'exec "$local_claude_bin" "$@"',
        "",
    ]
    return newline.join(lines)


def make_custom_legacy(project: Path) -> Path:
    """Create an npm-era layout in a custom directory with its real launcher."""

    root = make_legacy(project, local_dir=CUSTOM)
    (project / "bin" / "claude-local").write_text(
        npm_era_launcher(CUSTOM), encoding="utf-8"
    )
    return root


def test_launcher_names_the_custom_legacy_dir(tmp_path):
    launcher = tmp_path / "claude-local"
    launcher.write_text(npm_era_launcher(CUSTOM), encoding="utf-8")
    assert legacy_dir_from_launcher(launcher) == CUSTOM
    launcher.write_bytes(npm_era_launcher(CUSTOM, "\r\n").encode("utf-8"))
    assert legacy_dir_from_launcher(launcher) == CUSTOM
    # "$repo_root//dir" is still under the repository root, as bash runs it.
    launcher.write_text(npm_era_launcher("/" + CUSTOM), encoding="utf-8")
    assert legacy_dir_from_launcher(launcher) == CUSTOM
    for unsafe in ("../outside", "C:/abs", "a/../b", "~/npm", "$HOME/npm"):
        launcher.write_text(npm_era_launcher(unsafe), encoding="utf-8")
        assert legacy_dir_from_launcher(launcher) is None, unsafe
    unmarked = npm_era_launcher(CUSTOM).replace("# managed by claude-wrangler\n", "")
    launcher.write_text(unmarked, encoding="utf-8")
    assert legacy_dir_from_launcher(launcher) is None
    assert legacy_dir_from_launcher(tmp_path / "missing") is None


def test_launch_json_names_the_custom_legacy_dir(tmp_path):
    shim = tmp_path / "claude-local"
    shim.write_text("#!/bin/sh\n# managed by claude-wrangler\n", encoding="utf-8")
