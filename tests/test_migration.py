def test_cleanup_leaves_and_reports_entries_it_cannot_move(tmp_path, monkeypatch):
    legacy_dir = tmp_path / "npm"
    (legacy_dir / "node_modules").mkdir(parents=True)
    import claude_wrangler.migration as migration

    def refuse(path):
        raise PermissionError(5, "Access is denied")

    monkeypatch.setattr(migration, "remove_tree", refuse)
    monkeypatch.setattr(
        migration.os,
        "rename",
        lambda *a: (_ for _ in ()).throw(PermissionError(5, "x")),
    )
    result = cleanup_legacy_tree(legacy_dir, in_use=lambda path: False, txid="t")
    assert result.left and result.left[0][0] == "node_modules"
    assert (legacy_dir / "node_modules").exists()


def test_rerun_migration_when_the_legacy_layout_is_newer(project):
    make_legacy(project)
    assert install(project, standard_source()) == 0
    # An older release reinstalls npm state and writes newer schema-1 metadata.
    make_legacy_again = make_legacy
    root = project / LEGACY
    for name in os.listdir(root):
        path = root / name
        if path.is_dir():
            import shutil

            shutil.rmtree(path)
        else:
            path.unlink()
    import shutil as _shutil

    _shutil.rmtree(project / "bin")
    make_legacy_again(project, version="2.1.296", generated_at="2027-01-01T00:00:00Z")

    assert install(project, standard_source()) == 0

    meta = native_metadata(project)
    assert meta["claude_version"] == "2.1.296"
    store = RuntimeStore(runtime(project), project_root=project)
    assert store.slot_record(store.read_pointer()).version == "2.1.296"


