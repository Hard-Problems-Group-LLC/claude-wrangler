def make_legacy(
    project: Path,
    *,
    version: str = "2.1.287",
    local_dir: str = LEGACY,
    channel: Optional[str] = "stable",
    with_metadata: bool = True,
    lockfile: Optional[str] = "valid",
    binary: Optional[bytes] = None,
    generated_at: str = "2026-06-01T00:00:00Z",
    extra_metadata: Optional[Dict[str, Any]] = None,
) -> Path:
    """Create an npm-era layout as older claude-wrangler releases left it."""

    root = project / local_dir
    scope = root / "node_modules" / "@anthropic-ai"
    wrapper = scope / "claude-code"
    (wrapper / "bin").mkdir(parents=True)
    (wrapper / "package.json").write_text(json.dumps({"version": version}), "utf-8")
    (wrapper / "bin" / "claude.exe").write_bytes(b"stub" * 100)
    platform_dir = scope / "claude-code-{}".format(KEY)
    platform_dir.mkdir()
    (platform_dir / binary_filename(KEY)).write_bytes(
        fake_binary(version, KEY) if binary is None else binary
    )
    (root / "package.json").write_text(
        json.dumps(
            {
                "name": "claude-local-managed-install",
                "private": True,
                "devDependencies": {CLAUDE_PACKAGE_NAME: version},
            }
        ),
        encoding="utf-8",
    )
    if lockfile == "valid":
        (root / "package-lock.json").write_text(
            json.dumps(
                {
                    "packages": {
                        "node_modules/{}".format(CLAUDE_PACKAGE_NAME): {
                            "version": version
                        }
                    }
                }
            ),
            encoding="utf-8",
        )
    elif lockfile == "corrupt":
        (root / "package-lock.json").write_text("{corrupt", encoding="utf-8")
    (root / ".npm-cache" / "_cacache").mkdir(parents=True)
    if with_metadata:
        payload = {
            "schema_version": 1,
            "script_name": "claude-wrangler",
            "script_version": "2026.6.11.1",
            "generated_at": generated_at,
            "project_root": str(project),
            "claude_selector": "latest",
            "claude_channel": channel,
            "claude_version": version,
            "shared_home": False,
            "reasonable_permissions_enabled": True,
            "version_source": "default stable channel request",
            "available_versions": {"stable": version, "latest": None, "next": None},
            "paths": {
                "local_dir": local_dir,
                "claude_home_dir": ".local/claude/HOME",
                "claude_config_dir": ".local/claude",
                "launcher": "bin/claude-local",
                "readme_local": "README-LOCAL-Start-Claude.md",
            },
        }
        payload.update(extra_metadata or {})
        (root / METADATA_FILENAME).write_text(json.dumps(payload), encoding="utf-8")
    (project / "bin").mkdir(exist_ok=True)
    (project / "bin" / "claude-local").write_text(OLD_LAUNCHER, encoding="utf-8")
    return root


@pytest.fixture
def project(tmp_path: Path) -> Path:
    """Return a project directory with a .git marker."""

    root = tmp_path / "project"
    (root / ".git").mkdir(parents=True)
    return root


def runtime(project: Path) -> Path:
    """Return the native runtime root."""

    return project / ".local" / "claude" / "wrangler"


def native_metadata(project: Path) -> Dict[str, Any]:
    """Read the schema-2 metadata."""

    return json.loads((runtime(project) / METADATA_FILENAME).read_text("utf-8"))


def install(project: Path, source, *args: str, **kwargs: Any) -> int:
    """Run an install-like operation with fake services."""

    return install_like_operation(
        make_config(project, *args), make_services(source, **kwargs)
    )


